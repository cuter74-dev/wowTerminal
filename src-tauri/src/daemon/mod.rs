//! 세션 데몬 (#153) — 업데이트/재시작에도 세션이 살아남게 한다.
//!
//! 앱(UI)은 언제든 재시작될 수 있지만(자동 업데이트의 `relaunch()`), 세션은 살아 있어야 한다.
//! 그래서 PTY(추후 SSH/SFTP)를 **UI보다 오래 사는 별도 프로세스**가 소유하고, UI는 로컬
//! 소켓으로 붙어 명령을 위임하고 이벤트를 받는다. 재시작 후에는 살아있는 세션에 다시 attach한다.
//!
//! 데몬은 별도 바이너리가 아니라 **같은 실행 파일의 `--daemon` 모드**다(`main.rs`) — 기존
//! 매니저·스토어를 그대로 재사용하기 위함.
//!
//! Phase 1은 유닉스(macOS/Linux)의 Unix 도메인 소켓만 지원한다. Windows(명명 파이프)는
//! 다음 단계이며, 그때까지 Windows는 기존 인프로세스 경로로 동작한다(무회귀).

pub mod proto;

#[cfg(unix)]
pub mod client;
#[cfg(unix)]
pub mod server;

